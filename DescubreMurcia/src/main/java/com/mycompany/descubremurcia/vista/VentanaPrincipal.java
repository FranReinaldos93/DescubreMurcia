            int anchoDisp = lblimagen.getWidth();
    int altoDisp = lblimagen.getHeight();
    if (iconoOriginal != null && anchoDisp > 0 && altoDisp > 0) {
        double escala = Math.min(
        (double) anchoDisp / iconoOriginal.getIconWidth(),
        (double) altoDisp / iconoOriginal.getIconHeight());
        int w = (int) (iconoOriginal.getIconWidth() * escala);
        int h = (int) (iconoOriginal.getIconHeight() * escala);
        lblimagen.setIcon(new ImageIcon(
                iconoOriginal.getImage().getScaledInstance(w, h, Image.SCALE_SMOOTH)));
    }
        
