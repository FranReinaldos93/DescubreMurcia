    //metodo para posicionar el JDIALOG en función de la ventana principal
    private void posicionarDialogoAlLado(JFrame padre, JDialog dialogo) {
     Rectangle pantalla = padre.getGraphicsConfiguration().getBounds();

        int x = padre.getX() + padre.getWidth();   // a la derecha del JFrame
        int y = padre.getY();                      

        // Si no cabe a la derecha, lo ponemos a la izquierda
     if (x + dialogo.getWidth() > pantalla.x + pantalla.width) {
        x = padre.getX() - dialogo.getWidth();
        }

        dialogo.setLocation(x, y);
    }

    //metodo para el tamaño máximo de la ventana principal.
    private void limitarTamanoMaximo() {
    final Dimension maxSize = new Dimension(1100, 800);

    // Corrige el tamaño cuando el usuario se pasa del máximo
    addComponentListener(new ComponentAdapter() {
        @Override
        public void componentResized(ComponentEvent e) {
            int ancho = Math.min(getWidth(), maxSize.width);
            int alto = Math.min(getHeight(), maxSize.height);

            if (ancho != getWidth() || alto != getHeight()) {
                setSize(ancho, alto);
            }
        }
    });

    // Al pulsar maximizar, ocupará como mucho el tamaño máximo
    setMaximizedBounds(new Rectangle(0, 0, maxSize.width, maxSize.height));
    }
    
    
    //metodo realizado con ayuda de la IA para que el Dialogo al ser modal no habra más si ya está abierto
    private void abrirVentanaSecundaria(){
    
        if (dialogo == null || !dialogo.isDisplayable()) {
        // Si no hay ninguno, crea uno nuevo.
        dialogo = new DialogoSolicitud(this, false); 
        posicionarDialogoAlLado(this, dialogo);
        dialogo.setVisible(true);
        dialogo.setTitle("Descubre Murcia - Solicitud");
        } else {
        // Ya está abierto: se trae al frente
        dialogo.setVisible(true);
        dialogo.toFront();
        dialogo.requestFocus();
        }
    }

