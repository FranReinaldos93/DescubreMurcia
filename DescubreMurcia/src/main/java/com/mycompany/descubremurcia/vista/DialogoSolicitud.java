    //acción del combo box para según que actividad elejims que estén disponibles determinados servicios
    private void cbTipoActividadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbTipoActividadActionPerformed

        //enlazamos con el nº del combobox en el array para añadir el que queramos, teniendo en cuenta el 0 que desaparecerá la lista
        int indiceCombo = cbTipoActividad.getSelectedIndex();
        String[]lisAct = new String[2];
        
        switch(indiceCombo){
        
            case 0:
                jlistServicios.setVisible(false);
            break;
            case 1:
                jlistServicios.setVisible(true);
                lisAct[0]="Guia Cultural";
                lisAct[1]="audioguia";
                
            break;
            case 2:
                jlistServicios.setVisible(true);
                lisAct[0]="Guia ambiental";
                lisAct[1]="material para la actividad";
            break;
            case 3:
                jlistServicios.setVisible(true);
                lisAct[0]="Guia Cultural";
                lisAct[1]="audioguia";
            break;
        
        }
        jlistServicios.setListData(lisAct);
        jlistServicios.clearSelection();
    }//GEN-LAST:event_cbTipoActividadActionPerformed

