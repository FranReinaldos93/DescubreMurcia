        //Solicitar actividad--Crea una actividad y la muestra en un JOptionPane y cierra el formulario
    private void btnSolicitarActActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSolicitarActActionPerformed
        
        //Creación de variables y objeto Actividad
        String nombre=tfNom.getText();
        String telf = ftfTelf.getText();
        String tipoAct=(String) cbTipoActividad.getSelectedItem();
        Date fecha= (Date) spnFecha.getValue();
        int participantes= (int) spNumPart.getValue();
        boolean modalidad= rbIndividual.isSelected();
        String servicios= jlistServicios.getSelectedValue();
        Actividad nuevaActividad= new Actividad(nombre,telf,tipoAct,fecha,participantes,modalidad,servicios);
        
        //condicional para si hay algún dato vacio avisa pero no lo crea, si todo está correcto si
        if (nombre.trim().equals("") || telf.trim().equals("")|| tipoAct.equals("Selecione una actividad")){
        
            JOptionPane.showMessageDialog(this, "Revisa la información, falta algún dato imprescindible","Faltan datos",JOptionPane.ERROR_MESSAGE);
            
        }else{
        
            JOptionPane.showMessageDialog(this, nuevaActividad.toString(),"Actividad registrada",JOptionPane.INFORMATION_MESSAGE);
            dispose();
 
        }
        
        
    }//GEN-LAST:event_btnSolicitarActActionPerformed

